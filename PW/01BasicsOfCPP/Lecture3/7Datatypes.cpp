#include<iostream>
using namespace std;
int main(){
  cout << 5 + 2 << endl;
  cout << 5 - 2 << endl;
  cout << 5 * 2 << endl;


  cout << 5 / 2 << endl;           // int
  cout << 5 / 2.0 << endl;         // float
  cout << 5.0 / 2 << endl;         // float
  cout << 5.0 / 2.0 << endl;       // float
}